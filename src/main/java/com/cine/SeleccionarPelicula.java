    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
if (jComboBox1.getSelectedItem() == null
            || jComboBox2.getSelectedItem() == null
            || jComboBox3.getSelectedItem() == null) {
        return;
    }

    String pelicula = jComboBox1.getSelectedItem().toString();
    String salaSeleccionada = jComboBox2.getSelectedItem().toString();
    String funcionSeleccionadaTexto = jComboBox3.getSelectedItem().toString();

    if (pelicula.equals("Seleccionar película")) {
        JOptionPane.showMessageDialog(this, "Selecciona una película.");
        return;
    }

    if (salaSeleccionada.equals("Seleccionar sala")) {
        JOptionPane.showMessageDialog(this, "Selecciona una sala.");
        return;
    }

    if (funcionSeleccionadaTexto.equals("Seleccionar función")) {
        JOptionPane.showMessageDialog(this, "Selecciona una función.");
        return;
    }

    Funcion funcion = null;

    for (Funcion f : DatosCine.funciones) {

        String salaFuncion = "Sala " + f.getSala().getNumero()
                + " - " + f.getSala().getTipo();

        String funcionTexto = f.getHora() + " - " + f.getFecha();

        if (f.getPelicula().getNombre().equals(pelicula)
                && salaFuncion.equals(salaSeleccionada)
                && funcionTexto.equals(funcionSeleccionadaTexto)) {

            funcion = f;
            break;
        }
    }

    if (funcion == null) {
        JOptionPane.showMessageDialog(this,
                "No se encontró la función seleccionada.");
        return;
    }

    SeleccionarAsientos ventana = new SeleccionarAsientos();
    ventana.cargarFuncion(funcion);

    if (incluyeComida) {
        ventana.activarCompraConComida();
    }

    ventana.setVisible(true);
    this.dispose();
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jComboBox1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBox1ActionPerformed
 if (jComboBox1.getSelectedItem() == null) {
        return;
    }

    String pelicula = jComboBox1.getSelectedItem().toString();

    jComboBox2.removeAllItems();
    jComboBox3.removeAllItems();

    jComboBox2.addItem("Seleccionar sala");
    jComboBox3.addItem("Seleccionar función");

    for (Funcion f : DatosCine.funciones) {
        if (f.getPelicula().getNombre().equals(pelicula)) {

            String sala = "Sala " + f.getSala().getNumero()
                    + " - " + f.getSala().getTipo();

            boolean existe = false;

            for (int i = 0; i < jComboBox2.getItemCount(); i++) {
                if (jComboBox2.getItemAt(i).equals(sala)) {
                    existe = true;
                    break;
                }
            }

            if (!existe) {
                jComboBox2.addItem(sala);
            }
        }
    }
    }//GEN-LAST:event_jComboBox1ActionPerformed

    private void jComboBox2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBox2ActionPerformed
if (jComboBox2.getSelectedItem() == null) {
        return;
    }

    if (jComboBox1.getSelectedItem() == null) {
        return;
    }

    String sala = jComboBox2.getSelectedItem().toString();
    String pelicula = jComboBox1.getSelectedItem().toString();

    jComboBox3.removeAllItems();
    jComboBox3.addItem("Seleccionar función");

    for (Funcion f : DatosCine.funciones) {
        String salaFuncion = "Sala " + f.getSala().getNumero()
                + " - " + f.getSala().getTipo();

        if (f.getPelicula().getNombre().equals(pelicula)
                && salaFuncion.equals(sala)) {

            String funcion = f.getHora() + " - " + f.getFecha();

            jComboBox3.addItem(funcion);
        }
    }

    }//GEN-LAST:event_jComboBox2ActionPerformed

