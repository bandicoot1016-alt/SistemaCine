    private void mostrarAsientos() {
    jPanel1.setLayout(new java.awt.GridLayout(0, 10, 5, 5));
    jPanel1.removeAll();

    if (asientos == null) {
        return;
    }

    for (Asiento asiento : asientos) {
        JButton boton = new JButton(asiento.getFila() + asiento.getNumero());
boton.setFont(new java.awt.Font("Arial", java.awt.Font.PLAIN, 9));
boton.setMargin(new java.awt.Insets(0, 0, 0, 0));
        

        if (asiento.isOcupado()) {
            boton.setEnabled(false);
        }

        boton.addActionListener(e -> {
    if (asientosSeleccionados.contains(asiento)) {
        asientosSeleccionados.remove(asiento);
        boton.setText(asiento.getFila() + asiento.getNumero());
    } else {
        asientosSeleccionados.add(asiento);
        boton.setText("✓");
    }

    String seleccionados = "";

    for (Asiento seleccionado : asientosSeleccionados) {
        if (!seleccionados.isEmpty()) {
            seleccionados += ", ";
        }
        seleccionados += seleccionado.getFila() + seleccionado.getNumero();
    }

    jTextField1.setText(seleccionados);
});

        jPanel1.add(boton);
    }

    jPanel1.revalidate();
    jPanel1.repaint();
}
    
    public void cargarAsientos(ArrayList<Asiento> asientos) {
    this.asientos = asientos;
    mostrarAsientos();
}
    public void cargarFuncion(Funcion funcion) {
        this.funcion = funcion;
    this.asientos = funcion.getAsientos();
    mostrarAsientos();
}
    public void activarCompraConComida() {
    this.incluyeComida = true;
}
    
